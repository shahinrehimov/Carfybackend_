<?php

namespace App\Http\Requests\Admin\Faqs;

use App\Models\Faq;
use Illuminate\Foundation\Http\FormRequest;

class FaqChangeSortMultipleRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    public function rules(): array
    {
        return [
            'items'        => ['required', 'array', 'size:' . Faq::query()->count()],
            'items.*.id'   => ['required', 'integer', 'distinct', 'min:1'],
            'items.*.sort' => ['required', 'integer', 'min:0'],
        ];
    }
}
